print("--- Завдання 1: Обернути рядок в зворотному порядку ---")
original_string = "Програмування на Python"
# Використовуємо зріз (slicing) [::-1] для обертання рядка
reversed_string = original_string[::-1]

print(f"Початковий рядок: '{original_string}'")
print(f"Обернений рядок:  '{reversed_string}'")
print("-" * 50, "\n")


print("--- Завдання 2: Тестування функцій роботи з рядками ---")
# Створюємо тестовий рядок з зайвими пробілами та різним регістром
test_string = "   пРиВіт, чуДоВий СвіТе!   "
print(f"Оригінальний рядок для тестів: '{test_string}'\n")

# 1. strip() - видаляє пробіли на початку та в кінці рядка
print("1. Метод strip():")
print(f"Результат: '{test_string.strip()}'")

# 2. capitalize() - робить першу літеру великою, а всі інші маленькими
print("\n2. Метод capitalize() (застосуємо до очищеного рядка):")
clean_string = test_string.strip()
print(f"Результат: '{clean_string.capitalize()}'")

# 3. title() - робить першу літеру КОЖНОГО слова великою
print("\n3. Метод title():")
print(f"Результат: '{clean_string.title()}'")

# 4. upper() - переводить всі символи у верхній регістр
print("\n4. Метод upper():")
print(f"Результат: '{clean_string.upper()}'")

# 5. lower() - переводить всі символи у нижній регістр
print("\n5. Метод lower():")
print(f"Результат: '{clean_string.lower()}'")
print("-" * 50, "\n")


print("--- Завдання 3: Пошук дискримінанту квадратного рівняння ---")
# Функція для обчислення дискримінанту (Формула: D = b^2 - 4ac)
def find_discriminant(a, b, c):
    """
    Обчислює дискримінант квадратного рівняння ax^2 + bx + c = 0.
    """
    discriminant = (b ** 2) - (4 * a * c)
    return discriminant

# Тестування функції з різними значеннями
print("Рівняння виду: ax^2 + bx + c = 0")

# Тест 1: D > 0 (Два корені)
a1, b1, c1 = 1, -5, 6
d1 = find_discriminant(a1, b1, c1)
print(f"Тест 1 (a={a1}, b={b1}, c={c1}): Дискримінант D = {d1}")

# Тест 2: D = 0 (Один корінь)
a2, b2, c2 = 1, -4, 4
d2 = find_discriminant(a2, b2, c2)
print(f"Тест 2 (a={a2}, b={b2}, c={c2}): Дискримінант D = {d2}")

# Тест 3: D < 0 (Немає дійсних коренів)
a3, b3, c3 = 2, 1, 3
d3 = find_discriminant(a3, b3, c3)
print(f"Тест 3 (a={a3}, b={b3}, c={c3}): Дискримінант D = {d3}")
print("=" * 50)